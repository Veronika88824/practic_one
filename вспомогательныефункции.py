import time
import sys
import random

def print_slow(text, delay=0.03):
    """Медленный вывод текста для драматического эффекта"""
    for char in text:
        sys.stdout.write(char)
        sys.stdout.flush()
        time.sleep(delay)
    print()

def print_header(title):
    """Вывод заголовка"""
    print("\n" + "="*60)
    print(f"{title:^60}")
    print("="*60)

def clear_screen():
    """Очистка экрана консоли"""
    print("\n" * 100)

def roll_dice(sides=6):
    """Бросок кубика"""
    return random.randint(1, sides)

