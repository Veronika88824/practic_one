def show_loading_screen(message="Загрузка игры..."):
    """Показать экран загрузки"""
    print_header("ЗАГРУЗКА")
    print(f"\n{message}")
    
    for i in range(3):
        print(".", end='', flush=True)
        time.sleep(0.5)
    print("\n")
